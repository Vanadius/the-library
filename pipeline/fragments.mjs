// AUTHORED BLEED-THROUGH.
//
// A palimpsest is writing scraped away and written over, the older hand showing
// through. These are that older hand: real, authored sentences spliced — one at a
// time — into otherwise Markov-generated rooms. A true line surfacing in the
// salad, then the salad closing over it again.
//
// Their job is to teach the *texture* of intention before the exit does, so that
// recognizing the exit is a trained act rather than a lucky one. So they must be
// unmistakably *meant* — but they are deliberately NOT about the way out, never
// about doors or direction, and they are placed without regard to whether a room
// leads anywhere. Following the meaning is still a trap; these only teach you what
// meaning feels like. (See docs/NEXT_MOVEMENTS.md §1.)
//
// They are rendered identically to the surrounding noise — no glow, no flag.
// Recognition is the whole game. Swap or extend this pool freely; that you might
// want to is, as ever, the most on-theme thing about it.

